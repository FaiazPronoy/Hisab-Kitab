"""Writes EVALUATION.md from eval/out/results.json. Only measured numbers."""
import json
import os
import platform
from datetime import date
from pathlib import Path


def _t(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def write(s: dict, path: Path):
    ex = s["extraction_digital"]
    cfg = s["config"]
    lines = [
        "# Evaluation",
        "",
        f"Generated by `make eval` on {date.today().isoformat()}. Model: {cfg['llm_model']}. "
        f"Machine: {platform.machine()}, {platform.system()}, inside Docker. Seed {cfg['seed']}.",
        "",
        "Everything below was measured on this run. Synthetic invoices are generated by `eval/generator.py`, "
        "with ground truth written before rendering; 30% are a dev split used for tuning and are not scored here.",
        "",
        "## Headline",
        "",
        _t(["Metric", "Value"], [[k.replace("_", " "), v] for k, v in s["headline"].items()
                                   # the same figures are kept under a second name for older reports
                                   if k not in ("hallucination_rate", "routing_recall", "routing_recall_reached", "confidence_intervals")]),
        "",
    ]
    if "comparison" in s:
        comp = s["comparison"]
        m_s = comp.get("mock", {})
        g_s = comp.get("gemini", {})
        m_head = m_s.get("headline", {})
        g_head = g_s.get("headline", {})
        m_cost = m_s.get("cost", {}).get("cost_usd", 0.0) if m_s.get("cost") else 0.0
        g_cost = g_s.get("cost", {}).get("cost_usd", 0.0) if g_s.get("cost") else 0.0
        m_lines = m_s.get("extraction_digital", {}).get("line_items", {}).get("f1", 0.0)
        g_lines = g_s.get("extraction_digital", {}).get("line_items", {}).get("f1", 0.0)
        g_cfg = g_s.get("config", {})
        g_name = str(g_cfg.get("llm_model", "Gemini")).replace("gemini-", "Gemini ").replace("-flash-lite", " Flash-Lite").replace("-flash", " Flash")
        g_rel = g_s.get("reliability", {})
        g_failed = g_rel.get("failed", 0)
        g_note = (f"Both columns were measured on the same generated dataset (seed {g_cfg.get('seed')}, "
                  f"{g_cfg.get('n_generated')} invoices) with the same code. ")
        if g_failed:
            causes = "; ".join(f"{k.replace(' | ', ', ')}: {v}" for k, v in g_s.get("failure_causes", {}).items())
            g_note += (f"{g_failed} of the {g_rel.get('documents')} documents failed in the Gemini run "
                       f"({causes or 'see failure causes'}). ")
        else:
            g_note += f"No document failed in the Gemini run ({g_rel.get('documents')} documents). "
        g_note += ("The Gemini cost is estimated from the token counts at paid-tier prices; "
                   "the run used the free AI Studio tier, so nothing was billed.")
        comp_rows = [
            ["digital macro f1", m_head.get("digital_macro_f1"), g_head.get("digital_macro_f1")],
            ["digital all key fields correct", m_head.get("digital_all_key_fields_correct"), g_head.get("digital_all_key_fields_correct")],
            ["hallucination rate", m_head.get("hallucination_rate"), g_head.get("hallucination_rate")],
            ["routing recall", m_head.get("routing_recall"), g_head.get("routing_recall")],
            ["line items f1", m_lines, g_lines],
            ["segmentation accuracy", m_head.get("segmentation_accuracy"), g_head.get("segmentation_accuracy")],
            ["success rate", m_head.get("success_rate"), g_head.get("success_rate")],
            ["total cost (USD)", f"${m_cost:.4f}" if isinstance(m_cost, (int, float)) else str(m_cost),
                                f"${g_cost:.4f}" if isinstance(g_cost, (int, float)) else str(g_cost)],
        ]
        lines += [
            "## Rule-based baseline vs LLM",
            "",
            _t(["Metric", "Rule parser (mock)", g_name], comp_rows),
            "",
            g_note,
            "",
        ]
        if s.get("comparison_note"):
            lines += [s["comparison_note"], ""]
    lines += [
        f"## Extraction, digital PDFs (n = {ex['n']})",
        "",
        _t(["Field", "Precision", "Recall", "F1", "Hallucinations", "Abstentions", "n with value"],
           [[f, v["precision"], v["recall"], v["f1"], v["hallucinations"], v["abstentions"], v["n_true"]] for f, v in ex["per_field"].items()]),
        "",
        f"Macro F1 {ex['macro_f1']}. All key fields correct on {ex['all_key_fields_correct']} of invoices. "
        f"Hallucination rate (value given where the truth is empty) {ex['hallucination_rate']}; "
        f"wrong-value rate among given values {ex['wrong_value_rate']}.",
        "",
        f"Line items: precision {ex['line_items']['precision']}, recall {ex['line_items']['recall']}, "
        f"F1 {ex['line_items']['f1']}, cell accuracy {ex['line_items']['cell_accuracy']} (n = {ex['line_items']['n_true']} true rows).",
        "",
        "## Extraction on scans, by degradation tier",
        "",
        _t(["Tier", "n", "Macro F1", "All key fields correct", "Hallucination rate"],
           [[t, v["n"], v["macro_f1"], v["all_key_fields_correct"], v["hallucination_rate"]] for t, v in s["extraction_scans"].items()]),
        "",
    ]
    if s.get("ocr_engines"):
        rows = [[eng, tier, v["n"], v["cer"], v["sec_per_page"]] for eng, tiers in s["ocr_engines"].items() for tier, v in tiers.items()]
        lines += ["## OCR engines (character error rate against the clean text layer)", "",
                  _t(["Engine", "Tier", "Pages", "CER", "Seconds per page"], rows), ""]
    lines += [
        "## Validation on planted problems",
        "",
        _t(["Planted problem", "n", "Caught and routed to review", "Recall"],
           [[k, v["n"], v["caught"], v["recall"]] for k, v in s["validation"].items()]),
        "",
        f"Routing recall (invoices with any wrong key field or planted problem that went to review): "
        f"{s['routing'].get('routing_recall_all', s['routing']['routing_recall'])} ({s['routing']['wrong_to_review']}/{s['routing']['wrong']}) over all wrong or planted documents; "
        f"recall over documents reaching routing: {s['routing'].get('routing_recall_reached', s['routing']['routing_recall'])} "
        f"({s['routing'].get('wrong_reached_to_review', s['routing']['wrong_to_review'])}/{s['routing'].get('wrong_reached', s['routing']['wrong'])}). "
        f"Auto-accepted but wrong: {s['routing']['auto_accepted_wrong']}. "
        f"Clean invoices sent to review anyway: {s['routing']['false_review_rate']} ({s['routing']['clean_flagged']}/{s['routing']['clean']}).",
        "",
        "## Multi-invoice PDFs",
        "",
        f"{s['segmentation']['exact']} of {s['segmentation']['files']} files split into the right number of invoices "
        f"(over-split {s['segmentation']['over']}, under-split {s['segmentation']['under']}).",
        "",
        "## Reconciliation against a ledger with planted discrepancies",
        "",
        _t(["Category", "Planted", "Found", "Recall"],
           [[k, v["n"], v["found"], v["recall"]] for k, v in s["reconciliation"].items() if isinstance(v, dict)]),
        "",
        f"Precision over all non-matched items: {s['reconciliation'].get('precision_overall')}.",
        "",
        "## Failure handling",
        "",
        _t(["File", "Expected", "Got", "Error code"], [[z["file"], z["expect"], z["got"], z["error_code"]] for z in s["failure_zoo"]]),
        "",
    ]
    if s.get("failure_causes"):
        lines += [
            "## Failure taxonomy",
            "",
            _t(["Error code", "Parsed category", "Count"],
               [[k.split(" | ")[0] if " | " in k else k,
                 k.split(" | ")[1] if " | " in k else "-",
                 v]
                for k, v in s["failure_causes"].items()]),
            "",
        ]

    measured_paths = [
        Path(os.environ.get("BIG_DIR", "/data/storage/big")) / "measured.json",
        Path("data/big/measured.json"),
        Path("eval/out/measured.json"),
    ]
    for mp in measured_paths:
        if mp.exists():
            try:
                m_data = json.loads(mp.read_text(encoding="utf-8"))
                m_results = m_data.get("results", m_data) if isinstance(m_data, dict) else m_data
                if isinstance(m_results, list) and m_results:
                    bench_rows = [
                        [r.get("file"), r.get("pages"), r.get("workers", "1 worker"),
                         r.get("wall_seconds"), r.get("pages_per_minute"),
                         f"{r.get('peak_worker_rss_mb')} MB" if r.get('peak_worker_rss_mb') else "-",
                         r.get("pages_failed", 0)]
                        for r in m_results
                    ]
                    commit_tag = f" (commit {m_data.get('commit')})" if isinstance(m_data, dict) and m_data.get("commit") else ""
                    lines += [
                        f"## Large document throughput{commit_tag}",
                        "",
                        _t(["File", "Pages", "Workers", "Wall time (s)", "Pages/min", "Peak worker RSS", "Failed pages"], bench_rows),
                        "",
                    ]
                    break
            except Exception:
                pass

    if s.get("sroie") and s["sroie"].get("n"):
        sr = s["sroie"]
        gs = (s.get("comparison") or {}).get("gemini", {}).get("sroie")
        head = ["Field", "Rule parser (mock)"] + (["Gemini"] if gs else [])
        rows = [[f, f"{v['right']} of {v['n']}"] + ([f"{gs['fields'][f]['right']} of {gs['fields'][f]['n']}"] if gs else [])
                for f, v in sr["fields"].items()]
        lines += [
            "## Real receipts (ICDAR 2019 SROIE)",
            "",
            f"{sr['n']} scanned receipts from the public SROIE benchmark (every 16th image of its labelled set), "
            "downloaded at run time and not stored in the repo. Exact match after normalising: company letters and digits, "
            "the date as a calendar date, the total as a number.",
            "",
            _t(head, rows),
            "",
            f"All three right on {sr['all_three_right']} of {sr['n']} receipts with the rule parser"
            + (f" and {gs['all_three_right']} of {gs['n']} with Gemini" if gs else "") + ". "
            "The rule parser looks for printed labels such as \"Total\", which receipts often leave out.",
            "",
        ]
    if s.get("learning"):
        lr = s["learning"]
        n_sup, each = lr["suppliers"], lr["invoices_each"]
        rows = [[k + 1, f"{lr['off']['by_position'][k]['right_first_time']} of {lr['off']['by_position'][k]['n']}",
                 f"{lr['on']['by_position'][k]['right_first_time']} of {lr['on']['by_position'][k]['n']}"] for k in range(each)]
        b = lr["on"]["bank"]
        lines += [
            "## Supplier memory and supplier history",
            "",
            f"{n_sup} suppliers send {each} invoices each, every supplier printing its invoice number after its own label "
            f"({', '.join(lr['labels'])}). A simulated reviewer fixes a wrong number and approves each invoice. "
            "The same stream runs with supplier memory off and on.",
            "",
            _t(["Invoice from the supplier", "Number right first time, memory off", "Memory on"], rows),
            "",
            f"Numbers the reviewer had to fix: {lr['off']['corrections']} with memory off, {lr['on']['corrections']} with it on. "
            f"Invoices sent to review: {lr['off']['reviews']} and {lr['on']['reviews']}.",
            "",
            f"Changed bank details: {b['caught']} of {b['planted']} planted IBAN changes stopped by BANK_CHANGED; "
            f"{b['false_alarms']} false alarms on {b['genuine_with_history']} genuine invoices that had history.",
            "",
        ]
        gl = (s.get("comparison") or {}).get("gemini", {}).get("learning")
        if gl:
            right = sum(p["right_first_time"] for p in gl["off"]["by_position"])
            total = sum(p["n"] for p in gl["off"]["by_position"])
            lines += [f"With Gemini the numbers were right first time on {right} of {total} invoices even with memory off, "
                      "since the model reads unfamiliar labels; memory matters for the rule parser and for layouts a model misreads. "
                      f"Gemini run: {gl['on']['bank']['caught']} of {gl['on']['bank']['planted']} bank changes stopped, "
                      f"{gl['on']['bank']['false_alarms']} false alarms.", ""]
    lines += [
        "## Reliability, speed and cost",
        "",
        f"Documents: {s['reliability']['documents']}, success rate {s['reliability']['success_rate']}, "
        f"completed with errors {s['reliability']['completed_with_errors']}, failed {s['reliability']['failed']}.",
        "",
        f"Seconds per document, p50 {s['performance']['doc_seconds_p50']}, p95 {s['performance']['doc_seconds_p95']} "
        "(one process, tasks inline).",
        "",
        _t(["Page source", "Pages", "p50 ms", "p95 ms"],
           [[k, v["n"], round(v["p50"] or 0), round(v["p95"] or 0)] for k, v in (s["performance"]["page_timing_ms"] or {}).items()]),
        "",
    ]

    cost_info = s.get("cost") or {}
    total_cost = cost_info.get("cost_usd", 0.0)
    total_tokens = cost_info.get("tokens", 0)
    calls = cost_info.get("calls", 0)
    num_docs = s.get("reliability", {}).get("documents", 0)
    pt = s.get("performance", {}).get("page_timing_ms") or {}
    total_pages = sum(v.get("n", 0) for v in pt.values()) if pt else num_docs
    cost_per_doc = (total_cost / num_docs) if num_docs else 0.0
    cost_per_1k_pages = (total_cost / total_pages * 1000) if total_pages else 0.0

    lines += [
        f"LLM: {calls} calls, {total_tokens:,} tokens (including thinking tokens), ${total_cost:.4f} total.",
        f"Cost per document: ${cost_per_doc:.4f} (${cost_per_doc * 1000:.2f} per 1,000 documents).",
        f"Cost per 1,000 pages: ${cost_per_1k_pages:.2f} (measured across {total_pages} processed pages).",
        "",
        "## Limitations",
        "",
        "- The main set is synthetic. Layouts are varied but cleaner than real supplier invoices.",
        "- Scans are simulated degradation of rendered PDFs, not phone photos.",
        "- The rule parser is template-aware, which makes the baseline comparison weak against unseen real-world templates.",
        "- The clean-versus-medium scan result is unexplained at n = 15 per tier.",
        f"- False-review rate on clean invoices is {s['routing']['false_review_rate']} ({s['routing']['clean_flagged']}/{s['routing']['clean']}), reflecting conservative confidence thresholds.",
        "- Small planted counts per category limit statistical confidence.",
        "- The free Gemini tier may log or use data for product improvement.",
    ]
    if cfg.get("llm_provider") != "gemini":
        lines.append("- With the mock provider the numbers measure the rule-based parser, not an LLM.")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
